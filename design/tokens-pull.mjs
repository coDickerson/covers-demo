// pnpm tokens:pull — design/tokens.json (Figma variables) → apps/web/styles/tokens.css + apps/web/lib/tokens.ts
// Accepts a flat { "color/bg/canvas": "#F4F2F0" } map, or nested objects whose leaves are values or { $value | value }
// (the shapes most Figma variable-export plugins produce). Prints which tokens changed.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'design/tokens.json');
const cssOut = join(root, 'apps/web/styles/tokens.css');
const tsOut = join(root, 'apps/web/lib/tokens.ts');

function flatten(node, path = [], out = {}) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('_') || k.startsWith('$')) continue;
    const p = [...path, ...k.split('/')];
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      const leaf = v.$value ?? v.value;
      if (leaf !== undefined && typeof leaf !== 'object') out[p.join('/')] = leaf;
      else flatten(v, p, out);
    } else out[p.join('/')] = v;
  }
  return out;
}

const tokens = flatten(JSON.parse(readFileSync(src, 'utf8')));
const css = (name) => `--${name.replace(/\//g, '-')}`;

function cssValue(name, v) {
  if (name.startsWith('color/')) return String(v).toUpperCase();
  if (name.startsWith('motion/ease/')) return `cubic-bezier(${v})`;
  if (name.startsWith('motion/')) return `${v}ms`;
  if (name === 'stamp/rotation') return `${v}deg`;
  if (name.startsWith('type/weight/')) return String(v);
  if (name.startsWith('type/family/')) return `"${v}", ui-sans-serif, system-ui, sans-serif`;
  if (typeof v === 'number') return `${v}px`;
  return String(v);
}

const raw = Object.entries(tokens).map(([n, v]) => `  ${css(n)}: ${cssValue(n, v)};`);

// Tailwind v4 theme: colors replace the default palette (so only tokens exist), plus type, radius, spacing, easing.
const theme = ['  --color-*: initial;'];
for (const [n, v] of Object.entries(tokens)) {
  const val = cssValue(n, v);
  if (n.startsWith('color/')) theme.push(`  ${css(n)}: ${val};`);
  else if (n.startsWith('type/size/')) theme.push(`  --text-${n.split('/')[2]}: ${val};`);
  else if (n.startsWith('type/weight/')) theme.push(`  --font-weight-${n.split('/')[2]}: ${val};`);
  else if (n === 'type/family/sans') theme.push(`  --font-sans: var(--font-inter-tight), ${val};`);
  else if (n.startsWith('radius/')) theme.push(`  --radius-${n.split('/')[1]}: ${val};`);
  else if (n.startsWith('motion/ease/')) theme.push(`  --ease-${n.split('/')[2]}: ${val};`);
}
theme.push(`  --spacing: ${cssValue('space/1', tokens['space/1'] ?? 4)};`);

const header = '/* GENERATED by design/tokens-pull.mjs from design/tokens.json. Do not edit; change Figma and run pnpm tokens:pull. */';
const out = `${header}\n\n:root {\n${raw.join('\n')}\n}\n\n@theme {\n${theme.join('\n')}\n}\n`;

const before = existsSync(tsOut) ? (await import(`${tsOut}?t=${Date.now()}`).catch(() => null)) : null;
writeFileSync(cssOut, out);
writeFileSync(tsOut, `${header.replace('/*', '//').replace(' */', '')}\nexport const tokens = ${JSON.stringify(tokens, null, 2)} as const;\n`);

const prev = before?.tokens ?? {};
const changed = Object.keys({ ...prev, ...tokens }).filter((k) => prev[k] !== tokens[k]);
console.log(changed.length ? `Changed ${changed.length} token(s):\n${changed.map((k) => `  ${k}: ${prev[k] ?? '(new)'} → ${tokens[k] ?? '(removed)'}`).join('\n')}` : 'No token changes.');
console.log(`Wrote ${Object.keys(tokens).length} tokens.`);
